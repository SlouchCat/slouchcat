// The third output of the tokens (concept 27, 5.5): Kotlin for the Compose apps in android/.
//
//   node build-kotlin.mjs <out-dir>
//
// Writes <out-dir>/com/slouchcat/core/design/SlouchcatTokens.kt. Not part of `task gen`: the
// Android build runs it (android/core/design, task generateTokens) and keeps the result in its
// build folder, so dist/ and the web app stay as they are and nobody needs a JDK for them.
//
// Conversions:
// - colour `#RRGGBB` / `#RRGGBBAA` (DTCG) -> Color(0xAARRGGBB), the alpha turned to the front;
// - `rem` -> dp (1 rem = 16), `px` -> dp (1:1); font sizes as sp; `em` -> Compose em;
// - duration `120ms` -> Int (milliseconds); cubicBezier -> CubicBezierEasing;
// - fontWeight -> FontWeight; number -> Float.
// tokens-tv/*.json (group `tv`, the TV app of concept 26) come only into this output, not into the
// CSS of the web app.
// Left out, listed at the end of the file: font families (the apps use the system font) and
// container units such as `9cqi`, which Compose does not have.
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const out = process.argv[2];
if (!out) {
  console.error('usage: node build-kotlin.mjs <out-dir>');
  process.exit(2);
}
const pkg = path.dirname(fileURLToPath(import.meta.url));
const HEADER =
  'Generated by packages/design-tokens/build-kotlin.mjs from tokens/*.json. Do not edit.';

const pascal = (s) => s.replace(/(^|[-_ ])([a-z0-9])/gi, (_, __, c) => c.toUpperCase());
// Kotlin names may not start with a digit: surface.1 -> Surface.S1, space.4 -> Space.S4.
const ident = (s) => (/^[0-9]/.test(s) ? `S${s}` : pascal(s));
const number = (n) => (Number.isInteger(n) ? `${n}` : `${n}`.replace(/0+$/, ''));
let skipped = [];
// Fully qualified: the generated groups have names like Compose's types (SlouchcatTokens.Color).
const COLOR = 'androidx.compose.ui.graphics.Color';
const EASING = 'androidx.compose.animation.core.CubicBezierEasing';
const WEIGHT = 'androidx.compose.ui.text.font.FontWeight';

/** The Kotlin expression of one token, or null when Compose has no counterpart. */
function kotlinValue(token) {
  const v = token.$value;
  const type = token.$type;
  // A font size is sp, also when another token refers to one ({font.size.md}) or is named so.
  const original = String(token.original?.$value ?? '');
  const font = token.path.indexOf('font');
  const isFontSize =
    (font >= 0 && token.path[font + 1] === 'size') ||
    original.startsWith('{font.size.') ||
    /font-?size$/i.test(token.path.at(-1));
  switch (type) {
    case 'color': {
      const hex = String(v).replace('#', '');
      if (!/^([0-9a-f]{6}|[0-9a-f]{8})$/i.test(hex)) break;
      const alpha = hex.length === 8 ? hex.slice(6, 8) : 'ff';
      return `${COLOR}(0x${(alpha + hex.slice(0, 6)).toUpperCase()})`;
    }
    case 'dimension': {
      const m = String(v).match(/^(-?[0-9.]+)(rem|px|em)?$/);
      if (!m) break;
      const n = Number(m[1]);
      if (m[2] === 'em') return `${number(n)}.em`;
      const dp = m[2] === 'rem' ? n * 16 : n;
      return isFontSize ? `${number(dp)}.sp` : `${number(dp)}.dp`;
    }
    case 'duration': {
      const m = String(v).match(/^([0-9]+)ms$/);
      if (!m) break;
      return m[1];
    }
    case 'cubicBezier':
      if (!Array.isArray(v)) break;
      return `${EASING}(${v.map((x) => `${x}f`).join(', ')})`;
    case 'fontWeight':
      return `${WEIGHT}(${Number(v)})`;
    case 'number':
      return `${Number(v)}f`;
    default:
      break;
  }
  skipped.push(`${token.path.join('.')} (${type}: ${JSON.stringify(v)})`);
  return null;
}

function tree(tokens) {
  const root = {};
  for (const t of tokens) {
    let node = root;
    for (const seg of t.path.slice(0, -1)) node = node[ident(seg)] ??= {};
    const name = ident(t.path.at(-1));
    // on-accent and onAccent would both be OnAccent; one would silently win.
    if (node[name]) throw new Error(`two tokens become ${name}: ${t.path.join('.')}`);
    node[name] = t;
  }
  return root;
}

function emit(node, indent) {
  const lines = [];
  for (const [key, child] of Object.entries(node)) {
    if (child.$value !== undefined && child.path) {
      const value = kotlinValue(child);
      if (value === null) continue;
      if (child.$description) {
        lines.push(`${indent}/** ${child.$description.replace(/\*\//g, '* /')} */`);
      }
      lines.push(`${indent}val ${key} = ${value}`);
    } else {
      const inner = emit(child, `${indent}    `);
      if (inner.length) lines.push(`${indent}object ${key} {`, ...inner, `${indent}}`);
    }
  }
  return lines;
}

StyleDictionary.registerFormat({
  name: 'slouchcat/kotlin',
  format: ({ dictionary }) => {
    skipped = [];
    const body = emit(tree(dictionary.allTokens), '    ');
    return [
      `// ${HEADER}`,
      '@file:Suppress("unused")',
      '',
      'package com.slouchcat.core.design',
      '',
      'import androidx.compose.ui.unit.dp',
      'import androidx.compose.ui.unit.em',
      'import androidx.compose.ui.unit.sp',
      '',
      '/** The design tokens of packages/design-tokens, the same values the web app uses. */',
      'object SlouchcatTokens {',
      ...body,
      '}',
      '',
      ...skipped.map((s) => `// left out: ${s}`),
      '',
    ].join('\n');
  },
});

const dir = path.join(path.resolve(out), 'com/slouchcat/core/design');
mkdirSync(dir, { recursive: true });
const sd = new StyleDictionary({
  // tokens-tv/: the ten-foot sizes of the TV app (concept 26, 3.4), only in this output.
  source: [path.join(pkg, 'tokens/**/*.json'), path.join(pkg, 'tokens-tv/**/*.json')],
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    kotlin: {
      transforms: ['attribute/cti', 'name/camel'],
      buildPath: `${dir}/`,
      files: [{ destination: 'SlouchcatTokens.kt', format: 'slouchcat/kotlin' }],
    },
  },
});
await sd.buildAllPlatforms();
console.log(`SlouchcatTokens.kt written; left out ${skipped.length}: ${skipped.join('; ')}`);
