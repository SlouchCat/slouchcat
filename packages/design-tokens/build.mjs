// Builds dist/tokens.css, dist/index.js and dist/index.d.ts from the DTCG sources in tokens/.
// The output is generated; change tokens/*.json and run `task gen` instead of editing dist/.
import { rm } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';

const HEADER = 'Generated by packages/design-tokens/build.mjs from tokens/*.json. Do not edit.';

const camel = (segment) => segment.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** Nests the transformed token values by their camel-cased path. */
function toTree(tokens) {
  const tree = {};
  for (const token of tokens) {
    const path = token.path.map(camel);
    let node = tree;
    for (const key of path.slice(0, -1)) node = node[key] ??= {};
    node[path.at(-1)] = token.$value;
  }
  return tree;
}

/** Serialises a value tree as a readonly TypeScript literal type. */
function toType(value, indent = '') {
  if (typeof value !== 'object') return JSON.stringify(value);
  const inner = `${indent}  `;
  const members = Object.entries(value).map(
    ([key, child]) => `${inner}readonly ${JSON.stringify(key)}: ${toType(child, inner)};`,
  );
  return `{\n${members.join('\n')}\n${indent}}`;
}

const accentNamesOf = (tree) => Object.keys(tree.color.accent);

StyleDictionary.registerFormat({
  name: 'slouchcat/js',
  format: ({ dictionary }) => {
    const tree = toTree(dictionary.allTokens);
    return [
      `// ${HEADER}`,
      `export const tokens = ${JSON.stringify(tree, null, 2)};`,
      `export const accentNames = ${JSON.stringify(accentNamesOf(tree))};`,
      '',
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'slouchcat/dts',
  format: ({ dictionary }) => {
    const tree = toTree(dictionary.allTokens);
    const names = accentNamesOf(tree).map((name) => JSON.stringify(name));
    return [
      `// ${HEADER}`,
      `export declare const tokens: ${toType(tree)};`,
      `export declare const accentNames: readonly [${names.join(', ')}];`,
      'export type AccentName = (typeof accentNames)[number];',
      '',
    ].join('\n');
  },
});

// Value transforms shared by both platforms. Dimensions and durations stay as authored
// (rem, px, ms), so no size or time conversion is applied.
const valueTransforms = ['color/css', 'fontFamily/css', 'cubicBezier/css'];

await rm(new URL('./dist', import.meta.url), { recursive: true, force: true });

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    css: {
      transforms: ['attribute/cti', 'name/kebab', ...valueTransforms],
      prefix: 'sc',
      buildPath: 'dist/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: { outputReferences: false, fileHeader: () => [HEADER] },
        },
      ],
    },
    ts: {
      transforms: ['attribute/cti', 'name/camel', ...valueTransforms],
      buildPath: 'dist/',
      files: [
        { destination: 'index.js', format: 'slouchcat/js' },
        { destination: 'index.d.ts', format: 'slouchcat/dts' },
      ],
    },
  },
});

await sd.buildAllPlatforms();
